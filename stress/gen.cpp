// ============================================================
// 数据生成器
//
// 两条最重要的原则：
//   1. 小是刻意的。暴力只在 n <= 8 上跑得动。
//   2. 不要均匀随机。均匀随机几乎撞不到边界，而 bug 恰恰住在边界上。
//      要主动「过采样」极端情况：n=1、全相同、全 0、k=0……
// ============================================================
#include <bits/stdc++.h>
using namespace std;

mt19937 rng(chrono::steady_clock::now().time_since_epoch().count());

// [l, r] 闭区间
// 注意：rng() % (r - l) + l 取不到 r，是 off-by-one，别再用那个写法
int Int(int l, int r) { return l + (int)(rng() % (r - l + 1)); }

int main() {
    // 想复现某个反例，就把 seed 钉死
    // rng.seed(12345);

    // ---- 过采样极端值 ----
    int n = (rng() % 3 == 0) ? 1 : Int(1, 8);   // 1/3 概率直接把 n 打到 1
    int k = (rng() % 4 == 0) ? 0 : Int(0, 3);   // 1/4 概率 k = 0

    printf("1\n%d %d\n", n, k);                 // ← 按题面改

    // ---- 过采样退化情况：全相同 ----
    // 字母表也要小。用 26 个字母随机的串几乎不重复，
    // 而「有重复字符」才是大多数 bug 的来源。
    if (rng() % 5 == 0) {
        for (int i = 0; i < n; i++) putchar('a');            // 1/5 全同一个字符
    } else {
        for (int i = 0; i < n; i++) putchar('a' + Int(0, 2)); // 小字母表
    }
    puts("");
}
